"""
Academic Research & Audit Report Generator for MUREN AI.
Generates structured Markdown and print-ready HTML research reports
with model architecture parameters, detection tables, and temporal intervals.
"""
from datetime import datetime
from typing import Dict, Any, Optional
from ..core.config import settings


class ReportGeneratorService:
    """Generates publication-quality academic and audit reports."""

    @staticmethod
    def generate_image_markdown_report(result_data: Dict[str, Any]) -> str:
        date_str = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
        result_id = result_data.get("result_id", "N/A")
        w = result_data.get("original_width", 0)
        h = result_data.get("original_height", 0)
        ms = result_data.get("inference_time_ms", 0.0)
        preds = result_data.get("predictions", [])

        md = f"""# MUREN AI: Human-Object Interaction (HOI) Detection Report

**Generated:** {date_str}  
**Result ID:** `{result_id}`  
**Model Architecture:** Multi-scale Relation Network (MUREN) • ResNet-50 Backbone  
**Dataset Benchmark:** HICO-DET (117 Action Verbs, 80 Object Classes)  
**Checkpoint:** `hico-best.pth` (Epoch 81)  

---

## 1. Inference Telemetry & Input Specifications

| Parameter | Specification |
|---|---|
| Image Dimensions | {w} × {h} px |
| Model Device | CPU (Sequential Locked Engine) |
| Inference Latency | {ms:.1f} ms |
| Total Accepted Interactions | {len(preds)} |

---

## 2. Detected Human-Object Interactions

| Query ID | Subject | Action (Verb) | Target Object | Action Conf. | Object Conf. | Subject Bounding Box [x1, y1, x2, y2] | Object Bounding Box [x1, y1, x2, y2] |
|:---:|:---:|:---:|:---:|:---:|:---:|:---:|:---:|
"""
        for p in preds:
            qid = p.get("query_id", 0)
            sub = p.get("subject_label", "person")
            act = p.get("primary_action", "N/A")
            obj = p.get("object_label", "N/A")
            act_s = p.get("primary_action_score", 0.0)
            obj_s = p.get("object_score", 0.0)
            sb = [int(v) for v in p.get("subject_box", [0, 0, 0, 0])]
            ob = [int(v) for v in p.get("object_box", [0, 0, 0, 0])]

            md += f"| #{qid} | {sub} | **{act}** | {obj} | {act_s*100:.1f}% | {obj_s*100:.1f}% | `{sb}` | `{ob}` |\n"

        md += """
---

## 3. Top-3 Action Candidates per Interaction Query

"""
        for p in preds:
            qid = p.get("query_id", 0)
            act = p.get("primary_action", "N/A")
            obj = p.get("object_label", "N/A")
            top3 = p.get("top3_actions", [])

            md += f"### Query #{qid}: person → {act} → {obj}\n\n"
            for rank, a in enumerate(top3, 1):
                name = a.get("verb_name", "N/A")
                score = a.get("score", 0.0)
                md += f"- **Rank {rank}:** `{name}` ({score*100:.1f}%)\n"
            md += "\n"

        md += """---

*Report automatically generated by MUREN AI Visual Intelligence Engine.*
"""
        return md

